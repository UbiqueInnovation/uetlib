#!/usr/bin/env python3
"""Render repository dependency graphs from sibling uetlib Maven checkouts."""

import argparse
from collections import defaultdict
import json
from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET

NS = {"m": "http://maven.apache.org/POM/4.0.0"}
GROUPS = {"ch.uetlib", "ch.ubique.uetlib", "ch.ubique"}
TEST_REPOS = {"uetlib-test", "uetlib-spring-boot-test", "uetlib-testcontainers", "uetlib-testapp"}
COLORS = {"dependency": "#2563eb", "test": "#9333ea", "parent": "#64748b", "managed": "#94a3b8", "build": "#d97706"}


def text(element, name):
    if element is None:
        return ""
    return element.findtext("m:" + name, default="", namespaces=NS).strip()


def load_poms(workspace):
    poms = []
    owners = {}
    for repo in sorted(workspace.glob("uetlib-*")):
        if repo.name.startswith("uetlib-rust"):
            continue
        if not (repo / ".git").exists() or not (repo / "pom.xml").exists():
            continue
        paths = subprocess.check_output(
            ["git", "-C", str(repo), "ls-files", "--cached", "--others", "--exclude-standard", "-z"], text=True
        ).split("\0")
        for name in sorted(set(paths)):
            path = repo / name
            if path.name != "pom.xml" or not path.is_file():
                continue
            project = ET.parse(path).getroot()
            artifact = text(project, "artifactId")
            if artifact in owners and owners[artifact] != repo.name:
                raise ValueError(f"Artifact {artifact} belongs to multiple repositories")
            owners[artifact] = repo.name
            poms.append((repo.name, artifact, project))
    if not poms:
        raise ValueError("No sibling uetlib Maven checkouts found")
    return poms, owners


def references(poms, owners):
    edges = defaultdict(set)
    external = set()
    for repo, artifact, project in poms:
        parents = {child: parent for parent in project.iter() for child in parent}
        for element in project.iter():
            target = text(element, "artifactId")
            if target.startswith("uetlib-rust"):
                continue
            group = text(element, "groupId")
            if group == "${project.groupId}":
                group = text(project, "groupId") or text(project.find("m:parent", NS), "groupId")
            if group not in GROUPS or not target.startswith("uetlib-"):
                continue
            owner = owners.get(target, target)
            if owner == repo:
                continue
            if target not in owners:
                external.add(target)
            ancestors = []
            parent = parents.get(element)
            while parent is not None:
                ancestors.append(parent.tag.rsplit("}", 1)[-1])
                parent = parents.get(parent)
            kind = element.tag.rsplit("}", 1)[-1]
            if kind == "parent":
                kind = "parent"
            elif text(element, "scope") == "test":
                kind = "test"
            elif "dependencyManagement" in ancestors:
                kind = "managed"
            elif "build" in ancestors or kind in {"plugin", "path"}:
                kind = "build"
            else:
                kind = "dependency"
            edges[(repo, owner)].add((kind, f"{artifact} → {target}"))
    return edges, external


def render(path, nodes, edges, external):
    lines = [
        "// Generated by scripts/update_graphs.py from sibling Maven POMs.",
        "// Arrows point from a repository to the repository/artifact it references.",
        "digraph G {",
        '    graph [rankdir=LR, bgcolor="white", pad="0.3", nodesep="0.35", ranksep="1.0", splines=polyline];',
        '    node [shape=box, style="rounded,filled", fillcolor="#f1f5f9", color="#cbd5e1", fontname="Helvetica", fontsize=11];',
        '    edge [fontname="Helvetica", fontsize=9, arrowsize=0.65];',
    ]
    for name in sorted(nodes):
        attrs = {"label": name.replace("uetlib-", "uetlib\n", 1)}
        if name in external:
            attrs.update(style="rounded,dashed", tooltip="Referenced Maven artifact; source is outside this workspace")
        else:
            attrs.update(URL="https://github.com/UbiqueInnovation/" + name, target="_top", tooltip=name)
        lines.append(f"    {json.dumps(name)} [" + ", ".join(f"{k}={json.dumps(v, ensure_ascii=False)}" for k, v in attrs.items()) + "];")
    for (source, target), refs in sorted(edges.items()):
        kinds = sorted({kind for kind, _ in refs})
        primary = next(kind for kind in COLORS if kind in kinds)
        attrs = {"label": ", ".join(kinds), "color": COLORS[primary], "tooltip": "\n".join(sorted(detail for _, detail in refs))}
        if primary in {"parent", "managed", "build"}:
            attrs["style"] = "dotted" if primary == "managed" else "dashed"
        lines.append(f"    {json.dumps(source)} -> {json.dumps(target)} [" + ", ".join(f"{k}={json.dumps(v, ensure_ascii=False)}" for k, v in attrs.items()) + "];")
    lines.append("}")
    path.write_text("\n".join(lines) + "\n")
    subprocess.run(["dot", "-Tsvg", str(path), "-o", str(path) + ".svg"], check=True)


def main():
    entry = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workspace", type=Path, default=entry.parent)
    args = parser.parse_args()
    poms, owners = load_poms(args.workspace)
    edges, external = references(poms, owners)
    repos = set(owners.values())
    render(entry / "graph.dot", repos | external, edges, external)
    non_test = {
        pair: {(kind, detail) for kind, detail in refs if kind != "test"}
        for pair, refs in edges.items() if not TEST_REPOS.intersection(pair)
    }
    non_test = {pair: refs for pair, refs in non_test.items() if refs}
    render(entry / "graph-no-tests.dot", (repos | external) - TEST_REPOS, non_test, external)
    testing = {
        pair: refs for pair, refs in edges.items()
        if pair[0] in TEST_REPOS or any(kind == "test" for kind, _ in refs)
    }
    nodes = TEST_REPOS & repos | {node for pair in testing for node in pair}
    render(entry / "graph-test.dot", nodes, testing, external)
    print(f"Rendered {len(repos)} repositories, {len(poms)} Maven modules and {len(edges)} repository references.")
    if external:
        print("Referenced artifacts outside the workspace: " + ", ".join(sorted(external)))


if __name__ == "__main__":
    main()
